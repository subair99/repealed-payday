#!/usr/bin/env bash
# Build the micro1 submission zip: run the grader gate, regenerate the results table, then zip
# code + docs + raw traces. Excludes .env, .venv, .git and caches.
set -euo pipefail
cd "$(dirname "$0")"
python -m pytest -q -p no:cacheprovider
mkdir -p docs/failure_traces
for f in deepseek_failures.txt opus_failures.txt docs_confirm_failures.txt confirm_summary.txt; do [ -f "$f" ] && mv "$f" docs/failure_traces/; done
rm -f pilot_results/*.partial results/*.partial
python regrade.py --dir pilot_results --out docs/RESULTS.md >/dev/null
{ echo "# Confirmation run (final code) — generated by \`python summarize.py\`"; echo; python summarize.py; } > docs/RESULTS_CONFIRMATION.md
grep -q "\[VIDEO LINK" README.md && echo "WARNING: README still has the video-link placeholder"
grep -q "\[TOTAL FROM OPENROUTER" README.md && echo "WARNING: README still has the cost placeholder"
OUT="../repealed-payday-submission.zip"
rm -f "$OUT"
python - "$OUT" <<'EOF'
import os, sys, zipfile
skip_dirs = {".git", ".venv", "__pycache__", ".pytest_cache"}
skip_files = {".env"}
with zipfile.ZipFile(sys.argv[1], "w", zipfile.ZIP_DEFLATED) as z:
    for root, dirs, files in os.walk("."):
        dirs[:] = [d for d in dirs if d not in skip_dirs]
        for f in files:
            if f in skip_files or f.endswith(".zip"):
                continue
            p = os.path.join(root, f)
            z.write(p, os.path.relpath(p, "."))
EOF
python - "$OUT" <<'EOF'
import os, sys, zipfile
z = zipfile.ZipFile(sys.argv[1]); names = z.namelist()
assert "README.md" in names and ".env" not in names, "README missing or .env included"
print(f"{sys.argv[1]}: {len(names)} files, {os.path.getsize(sys.argv[1])/1e6:.2f} MB")
EOF
